export function collectAllTojeongDisplayFields(): Record<string, string> {
  const f: Record<string, string> = {};
  for (const [id, h] of Object.entries(HEXAGRAMS_V3)) {
    const p = `hex.${id}`;
    f[`${p}.poem`] = h.poem;
    f[`${p}.meaning`] = h.meaning;
    f[`${p}.summary`] = h.summary;
    f[`${p}.advice`] = h.advice;
    f[`${p}.caution`] = h.caution;
  }
  for (const [i, m] of M_THEMES_V3.entries()) {
    f[`month.${i}.desc`] = m.desc;
  }
  for (const [k, c] of Object.entries(CAT_TEXT_V3)) {
    f[`cat.${k}.high`] = c.high;
    f[`cat.${k}.low`] = c.low;
    f[`cat.${k}.tip`] = c.tip;
  }
  return f;
}
