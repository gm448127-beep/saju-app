/** v3 카피 전체 린트 (CI) */
export function collectAllTodaySipsinCopyFields(): Record<string, string> {
  const f: Record<string, string> = {};
  const add = (prefix: string, v: string) => {
    f[prefix] = v;
  };
  for (const [k, v] of Object.entries(SIPSIN_RELATION_V3)) add(`relation.${k}`, v);
  for (const [k, v] of Object.entries(SIPSIN_DETAIL_V3)) add(`detail.${k}`, v);
  for (const [k, v] of Object.entries(TIPS_V3)) add(`tip.${k}`, v);
  for (const [k, v] of Object.entries(WARNINGS_V3)) add(`warn.${k}`, v);
  for (const [k, v] of Object.entries(TIME_ADVICE_V3_MAP)) {
    add(`time.${k}.am`, v.morning);
    add(`time.${k}.pm`, v.afternoon);
    add(`time.${k}.ev`, v.evening);
  }
  for (const [k, arr] of Object.entries(DO_DETAIL_V3)) {
    add(`do.${k}.r`, arr.reason);
    add(`do.${k}.a`, arr.action);
  }
  for (const [k, arr] of Object.entries(DONT_DETAIL_V3)) {
    add(`dont.${k}.r`, arr.reason);
    add(`dont.${k}.a`, arr.action);
  }
  return f;
}
